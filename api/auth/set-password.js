import { timingSafeEqual } from 'crypto';
import { applyCors } from '../lib/cors.js';
import {
  normalizeEmail,
  isValidEmail,
  isValidPassword,
  generatePassword,
  upsertPassword,
  passwordAuthConfigured,
} from '../lib/password-auth.js';
import { getStripe, findActiveSubscription } from '../lib/stripe.js';
import { consumeRateLimit, rateLimitResponse } from '../lib/rate-limit.js';

function readBody(req) {
  if (!req.body) return {};
  if (typeof req.body === 'string') {
    try { return JSON.parse(req.body); } catch { return {}; }
  }
  return req.body;
}

function secretsEqual(a, b) {
  const left = Buffer.from(String(a || ''), 'utf8');
  const right = Buffer.from(String(b || ''), 'utf8');
  if (left.length === 0 || right.length === 0 || left.length !== right.length) {
    // Comparação dummy do mesmo tamanho para não vazar comprimento via timing
    // quando um dos lados está vazio — ainda rejeita.
    const pad = Buffer.alloc(32);
    timingSafeEqual(pad, pad);
    return false;
  }
  return timingSafeEqual(left, right);
}

/**
 * POST /api/auth/set-password
 * Bootstrap: header x-bootstrap-secret === BOOTSTRAP_SECRET
 */
export default async function handler(req, res) {
  applyCors(req, res, { credentials: true });
  if (req.method === 'OPTIONS') return res.status(204).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  const limited = await consumeRateLimit(req, { limit: 5, windowMs: 15 * 60_000, keyPrefix: 'set-password' });
  if (limited) return rateLimitResponse(res, limited.retryAfterSec);

  const secret = String(process.env.BOOTSTRAP_SECRET || '').trim();
  const given = String(req.headers['x-bootstrap-secret'] || '').trim();
  if (!secret || !secretsEqual(given, secret)) {
    return res.status(401).json({ error: 'Não autorizado' });
  }
  if (!passwordAuthConfigured()) {
    return res.status(503).json({ error: 'Stripe não configurado' });
  }

  const { email, password: givenPassword, force = false } = readBody(req);
  const cleanEmail = normalizeEmail(email);
  if (!isValidEmail(cleanEmail)) {
    return res.status(400).json({ error: 'E-mail inválido' });
  }

  try {
    const stripe = getStripe();
    const list = await stripe.customers.list({ email: cleanEmail, limit: 5 });
    const customer = list.data.find((c) => !c.deleted) || list.data[0];
    if (!customer && !force) {
      return res.status(404).json({ error: 'Cliente Stripe não encontrado' });
    }
    if (customer) {
      const sub = await findActiveSubscription(customer.id);
      if (!sub && !force) {
        return res.status(402).json({ error: 'Assinatura inativa' });
      }
    }

    const autoGenerated = !(givenPassword && isValidPassword(givenPassword));
    const password = autoGenerated
      ? generatePassword(14)
      : String(givenPassword);

    const saved = await upsertPassword(cleanEmail, password, {
      customerId: customer?.id || null,
      overwrite: true,
    });

    // Nunca ecoar palavra-passe fornecida pelo cliente (WEB-013).
    // Só devolve a gerada automaticamente — o operador bootstrap precisa dela uma vez.
    const body = {
      ok: true,
      email: cleanEmail,
      customerId: saved.customerId,
    };
    if (autoGenerated) body.password = password;
    return res.status(200).json(body);
  } catch (e) {
    console.error('[auth/set-password]', e?.message || e);
    return res.status(500).json({ error: e.message || 'set_password_error' });
  }
}
